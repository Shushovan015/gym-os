), projection(schema_name, table_name, expected_columns) AS (VALUES
  ('public', 'profiles', ARRAY['id','role']),
  ('auth', 'users', ARRAY['id','email','email_confirmed_at','banned_until','deleted_at']),
  ('storage', 'buckets', ARRAY['id','public']),
  ('storage', 'objects', ARRAY['bucket_id','name','metadata','updated_at']),
  ('gym_export_scope', 'approved_staff', ARRAY['id']),
  ('gym_export_scope', 'staff', ARRAY['id','email','email_confirmed_at','banned_until','deleted_at','source_role']),
  ('gym_export_scope', 'storage_buckets', ARRAY['id','public']),
  ('gym_export_scope', 'storage_objects', ARRAY['bucket_id','name','bytes','mime','etag','updated_at'])
), candidates(role_name) AS (VALUES ('gym_export_reader'), ('gym_export_login')),
roles AS (
  SELECT wanted.role_name, actual.*
  FROM candidates wanted LEFT JOIN pg_roles actual ON actual.rolname = wanted.role_name
), relations AS (
  SELECT n.nspname AS schema_name, c.* FROM pg_class c JOIN pg_namespace n ON n.oid = c.relnamespace
  WHERE c.relkind IN ('r','p','v','m','f')
    AND (n.nspname = 'public' OR n.nspname = 'gym_export_scope' OR EXISTS (
      SELECT 1 FROM projection p WHERE p.schema_name = n.nspname AND p.table_name = c.relname
    ))
), columns AS (
  SELECT r.schema_name, r.relname, r.oid, a.attnum, a.attname, a.attnotnull, a.attacl,
    replace(replace(format_type(a.atttypid, a.atttypmod), 'character varying', 'varchar'), ', ', ',') AS data_type
  FROM relations r JOIN pg_attribute a ON a.attrelid = r.oid
  WHERE a.attnum > 0 AND NOT a.attisdropped
), current_public AS (
  SELECT c.* FROM columns c JOIN relations r USING (oid)
  WHERE c.schema_name = 'public' AND r.relkind IN ('r','p')
), routines AS (
  SELECT n.nspname, p.* FROM pg_proc p JOIN pg_namespace n ON n.oid = p.pronamespace
  WHERE n.nspname NOT IN ('pg_catalog','information_schema')
    AND (n.nspname IN ('public','auth','storage','gym_export_scope') OR p.prosecdef)
), acl_objects AS (
  SELECT 'schema' AS kind, n.nspname::text AS object_name, n.nspowner AS owner,
    coalesce(n.nspacl, acldefault('n', n.nspowner)) AS acl
  FROM pg_namespace n WHERE n.nspname IN ('public','auth','storage','gym_export_scope')
  UNION ALL
  SELECT 'relation', format('%I.%I', r.schema_name, r.relname), r.relowner,
    coalesce(r.relacl, acldefault('r', r.relowner)) FROM relations r
  UNION ALL
  SELECT 'column', format('%I.%I.%I', c.schema_name, c.relname, c.attname), r.relowner, c.attacl
    FROM columns c JOIN relations r USING (oid) WHERE c.attacl IS NOT NULL
  UNION ALL
  SELECT 'routine', format('%I.%I(%s)', p.nspname, p.proname, oidvectortypes(p.proargtypes)), p.proowner,
    coalesce(p.proacl, acldefault('f', p.proowner)) FROM routines p
), report(section, object_name, details) AS (
  SELECT '00_context', current_database()::text, jsonb_build_object(
    'serverVersion', current_setting('server_version_num'), 'observer', current_user,
    'coverage', 'Catalog only. Row completeness and role behavior require separate verification.')
  UNION ALL
  SELECT '01_scope', wanted.table_name, jsonb_build_object('scope', wanted.scope, 'exists', r.oid IS NOT NULL,
    'kind', r.relkind, 'partition', r.relispartition, 'inheritance', EXISTS (
      SELECT 1 FROM pg_inherits i WHERE i.inhrelid = r.oid OR i.inhparent = r.oid))
  FROM (SELECT table_name, 'core' AS scope FROM core UNION ALL SELECT table_name, 'optional' FROM optional) wanted
  LEFT JOIN relations r ON r.schema_name = 'public' AND r.relname = wanted.table_name
  UNION ALL
  SELECT '02_schema_diff', format('%I.%I', coalesce(b.table_name, c.relname), coalesce(b.column_name,c.attname)),
    jsonb_build_object('nov22Type', b.data_type, 'currentType', c.data_type,
      'status', CASE WHEN b.column_name IS NULL THEN 'added' WHEN c.attname IS NULL THEN 'missing' ELSE 'type changed' END)
  FROM baseline b FULL JOIN current_public c ON b.table_name = c.relname AND b.column_name = c.attname
  WHERE b.data_type IS DISTINCT FROM c.data_type
  UNION ALL
  SELECT '03_column', format('%I.%I.%I', c.schema_name,c.relname,c.attname),
    jsonb_build_object('type',c.data_type,'notNull',c.attnotnull,'position',c.attnum) FROM columns c
  UNION ALL
  SELECT '04_constraint', format('%I.%I.%I', r.schema_name,r.relname,k.conname),
    jsonb_build_object('type',k.contype,'validated',k.convalidated,'deferrable',k.condeferrable,
      'columns',(SELECT jsonb_agg(a.attname ORDER BY x.pos) FROM unnest(k.conkey) WITH ORDINALITY x(attnum,pos)
                 JOIN pg_attribute a ON a.attrelid = r.oid AND a.attnum = x.attnum),
      'references', CASE WHEN k.confrelid <> 0 THEN k.confrelid::regclass::text END,
      'referencedColumns',(SELECT jsonb_agg(a.attname ORDER BY x.pos) FROM unnest(k.confkey) WITH ORDINALITY x(attnum,pos)
                 JOIN pg_attribute a ON a.attrelid = k.confrelid AND a.attnum = x.attnum))
  FROM pg_constraint k JOIN relations r ON r.oid = k.conrelid
  UNION ALL
  SELECT '05_rls', format('%I.%I',r.schema_name,r.relname),
    jsonb_build_object('enabled',r.relrowsecurity,'forced',r.relforcerowsecurity,'owner',pg_get_userbyid(r.relowner))
  FROM relations r WHERE r.relkind IN ('r','p')
  UNION ALL
  SELECT '06_policy', format('%I.%I.%I',r.schema_name,r.relname,p.polname), jsonb_build_object(
    'schema',r.schema_name,'table',r.relname,'policyName',p.polname,
    'command',p.polcmd,'permissive',p.polpermissive,
    'principals',(SELECT jsonb_agg(CASE WHEN a = 0 THEN 'PUBLIC' ELSE pg_get_userbyid(a) END) FROM unnest(p.polroles) a),
    'appliesToExistingLogin', (SELECT bool_or(CASE WHEN a = 0 THEN true ELSE pg_has_role(x.oid,a,'USAGE') END)
      FROM unnest(p.polroles) a CROSS JOIN roles x WHERE x.role_name = 'gym_export_login' AND x.oid IS NOT NULL),
    'reviewRestrictiveForFutureLogin', NOT p.polpermissive AND p.polcmd IN ('r','*') AND 0 = ANY(p.polroles),
    'usingClass', CASE WHEN p.polqual IS NULL THEN 'none'
      WHEN pg_get_expr(p.polqual,r.oid) IN ('true','false') THEN pg_get_expr(p.polqual,r.oid) ELSE 'expression requires owner review' END,
    'withCheckPresent', p.polwithcheck IS NOT NULL)
  FROM relations r JOIN pg_policy p ON p.polrelid = r.oid
  UNION ALL
  SELECT '07_grant', a.object_name, jsonb_build_object('kind',a.kind,'owner',pg_get_userbyid(a.owner),
    'grantee',CASE WHEN g.grantee = 0 THEN 'PUBLIC' ELSE pg_get_userbyid(g.grantee) END,
    'privilege',g.privilege_type,'grantable',g.is_grantable)
  FROM acl_objects a CROSS JOIN LATERAL aclexplode(a.acl) g
  UNION ALL
  SELECT '08_routine', format('%I.%I(%s)', p.nspname,p.proname,oidvectortypes(p.proargtypes)),
    jsonb_build_object('securityDefiner',p.prosecdef,'owner',pg_get_userbyid(p.proowner),
      'schema',p.nspname,'routineName',p.proname,'argumentTypes',oidvectortypes(p.proargtypes),'routineKind',p.prokind,
      'publicExecute', EXISTS (SELECT 1 FROM aclexplode(coalesce(p.proacl,acldefault('f',p.proowner))) a
                              WHERE a.grantee = 0 AND a.privilege_type = 'EXECUTE'),
      'schemaUsageForExistingLogin',has_schema_privilege(x.oid,p.pronamespace,'USAGE'),
      'executeForExistingLogin',has_function_privilege(x.oid,p.oid,'EXECUTE'))
  FROM routines p CROSS JOIN roles x WHERE x.role_name = 'gym_export_login'
  UNION ALL
  SELECT '09_projection', format('%I.%I',p.schema_name,p.table_name), jsonb_build_object(
    'exists',r.oid IS NOT NULL,'kind',r.relkind,'owner',pg_get_userbyid(r.relowner),
    'securityBarrier',coalesce(r.reloptions @> ARRAY['security_barrier=true'],false),
    'securityInvoker',coalesce(r.reloptions @> ARRAY['security_invoker=true'],false),
    'baseRelations', ARRAY(
      SELECT DISTINCT format('%I.%I',bn.nspname,base.relname)
      FROM pg_rewrite rw JOIN pg_depend d ON d.classid = 'pg_rewrite'::regclass AND d.objid = rw.oid
      JOIN pg_class base ON d.refclassid = 'pg_class'::regclass AND base.oid = d.refobjid
      JOIN pg_namespace bn ON bn.oid = base.relnamespace
      WHERE rw.ev_class = r.oid AND base.oid <> r.oid
      ORDER BY 1),
    'missingColumns',ARRAY(SELECT unnest(p.expected_columns) EXCEPT SELECT c.attname::text FROM columns c WHERE c.oid = r.oid),
    'extraColumns',CASE WHEN p.schema_name = 'gym_export_scope' THEN
      ARRAY(SELECT c.attname::text FROM columns c WHERE c.oid = r.oid EXCEPT SELECT unnest(p.expected_columns)) END,
    'existingLoginCanRead',has_any_column_privilege(x.oid,r.oid,'SELECT'),
    'existingOwnerAssumableByLogin',pg_has_role(x.oid,r.relowner,'MEMBER'))
  FROM projection p LEFT JOIN relations r ON r.schema_name = p.schema_name AND r.relname = p.table_name
  CROSS JOIN roles x WHERE x.role_name = 'gym_export_login'
  UNION ALL
  SELECT '10_role', x.role_name, jsonb_build_object('exists',x.oid IS NOT NULL,'login',x.rolcanlogin,
    'superuser',x.rolsuper,'bypassRls',x.rolbypassrls,'createRole',x.rolcreaterole,'createDb',x.rolcreatedb,
    'replication',x.rolreplication,'globalReadMembership',pg_has_role(x.oid,'pg_read_all_data','MEMBER'),
    'canCreateSchema',has_database_privilege(x.oid,current_database(),'CREATE'),
    'schemaCreateGrants',ARRAY(SELECT n.nspname FROM pg_namespace n WHERE has_schema_privilege(x.oid,n.oid,'CREATE')),
    'memberships',ARRAY(SELECT y.rolname FROM pg_roles y WHERE y.oid <> x.oid AND pg_has_role(x.oid,y.oid,'MEMBER')))
  FROM roles x
  UNION ALL
  SELECT '11_effective_access', format('%I:%I.%I',x.role_name,n.nspname,c.relname), jsonb_build_object(
    'read',has_any_column_privilege(x.oid,c.oid,'SELECT'),
    'write',has_table_privilege(x.oid,c.oid,'INSERT, UPDATE, DELETE, TRUNCATE, TRIGGER')
      OR has_any_column_privilege(x.oid,c.oid,'INSERT, UPDATE'),
    'owner', x.oid = c.relowner,
    'approvedCore', n.nspname = 'public' AND EXISTS (SELECT 1 FROM core WHERE table_name = c.relname))
  FROM roles x CROSS JOIN pg_class c JOIN pg_namespace n ON n.oid = c.relnamespace
  WHERE x.oid IS NOT NULL AND n.nspname NOT IN ('pg_catalog','information_schema')
    AND n.nspname NOT LIKE 'pg_toast%' AND c.relkind IN ('r','p','v','m','f')
    AND (has_any_column_privilege(x.oid,c.oid,'SELECT, INSERT, UPDATE')
      OR has_table_privilege(x.oid,c.oid,'DELETE, TRUNCATE, TRIGGER') OR x.oid = c.relowner)
)
SELECT section, object_name, details FROM report ORDER BY section, object_name, details;
