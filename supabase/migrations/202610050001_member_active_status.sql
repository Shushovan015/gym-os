-- Create function to update member status with history tracking
CREATE OR REPLACE FUNCTION public.set_member_active_status(
    p_member_id bigint,
    p_is_active boolean,
    p_changed_by uuid DEFAULT NULL,
    p_notes text DEFAULT NULL
)
RETURNS void LANGUAGE plpgsql SECURITY DEFINER SET search_path = public AS $$
DECLARE
    v_member RECORD;
    v_old_status text;
    v_new_status text;
BEGIN
    -- Verify admin access
    IF NOT public.is_admin() THEN
        RAISE EXCEPTION 'Admin access required';
    END IF;

    -- Get current member
    SELECT * INTO v_member FROM public.members WHERE id = p_member_id FOR UPDATE;
    IF NOT FOUND THEN
        RAISE EXCEPTION 'Member not found';
    END IF;

    -- No change needed
    IF v_member.is_active = p_is_active THEN
        RETURN;
    END IF;

    v_old_status := CASE WHEN v_member.is_active THEN 'active' ELSE 'inactive' END;
    v_new_status := CASE WHEN p_is_active THEN 'active' ELSE 'inactive' END;

    -- Update member status
    IF p_is_active THEN
        UPDATE public.members
        SET is_active = true,
            activated_at = now(),
            deactivated_at = NULL,
            updated_at = now()
        WHERE id = p_member_id;
    ELSE
        UPDATE public.members
        SET is_active = false,
            deactivated_at = now(),
            activated_at = NULL,
            updated_at = now()
        WHERE id = p_member_id;
    END IF;

    -- Record status change in history
    INSERT INTO public.member_status_history (member_id, status, changed_by, notes)
    VALUES (p_member_id, v_new_status, p_changed_by, p_notes);
END $$;

ALTER FUNCTION public.set_member_active_status(bigint, boolean, uuid, text) OWNER TO postgres;

GRANT EXECUTE ON FUNCTION public.set_member_active_status(bigint, boolean, uuid, text) TO anon, authenticated, service_role;

