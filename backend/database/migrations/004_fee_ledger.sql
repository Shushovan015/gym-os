CREATE TABLE IF NOT EXISTS invoices (
    id BIGINT AUTO_INCREMENT PRIMARY KEY,
    invoice_number VARCHAR(255) NULL UNIQUE,
    member_ref BIGINT NULL,
    customer_name TEXT NOT NULL,
    customer_phone TEXT NULL,
    customer_email TEXT NULL,
    billing_date DATE NOT NULL,
    due_date DATE NULL,
    invoice_status VARCHAR(16) NOT NULL DEFAULT 'draft' CHECK (invoice_status IN ('draft','issued','cancelled')),
    payment_status VARCHAR(16) NOT NULL DEFAULT 'unpaid' CHECK (payment_status IN ('unpaid','partially_paid','paid')),
    currency_code CHAR(3) NOT NULL DEFAULT 'NPR',
    subtotal_minor BIGINT NOT NULL DEFAULT 0 CHECK (subtotal_minor >= 0),
    discount_minor BIGINT NOT NULL DEFAULT 0 CHECK (discount_minor >= 0),
    tax_minor BIGINT NOT NULL DEFAULT 0 CHECK (tax_minor >= 0),
    total_minor BIGINT NOT NULL DEFAULT 0 CHECK (total_minor >= 0),
    paid_minor BIGINT NOT NULL DEFAULT 0 CHECK (paid_minor >= 0),
    balance_minor BIGINT NOT NULL DEFAULT 0 CHECK (balance_minor >= 0),
    tax_enabled TINYINT(1) NOT NULL DEFAULT 0,
    tax_label VARCHAR(255) NOT NULL DEFAULT 'Tax',
    tax_rate_basis_points INT NOT NULL DEFAULT 0 CHECK (tax_rate_basis_points BETWEEN 0 AND 10000),
    notes TEXT NULL,
    inventory_applied_at DATETIME(6) NULL,
    cancelled_at DATETIME(6) NULL,
    cancellation_reason TEXT NULL,
    cancelled_by CHAR(36) CHARACTER SET ascii COLLATE ascii_bin NULL,
    created_by CHAR(36) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
    updated_by CHAR(36) CHARACTER SET ascii COLLATE ascii_bin NULL,
    created_at DATETIME(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6),
    updated_at DATETIME(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6) ON UPDATE CURRENT_TIMESTAMP(6),
    legacy_bill_id BIGINT NULL,
    legacy_source VARCHAR(255) NULL,
    FOREIGN KEY (member_ref) REFERENCES members(id) ON DELETE RESTRICT,
    CHECK (invoice_status = 'draft' OR (discount_minor <= subtotal_minor AND total_minor = subtotal_minor - discount_minor + tax_minor
        AND paid_minor <= total_minor AND balance_minor = total_minor - paid_minor)),
    INDEX (member_ref),
    INDEX (billing_date, id),
    INDEX (invoice_status, payment_status),
    INDEX (legacy_source, legacy_bill_id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_bin;

CREATE TABLE IF NOT EXISTS invoice_payments (
    id BIGINT AUTO_INCREMENT PRIMARY KEY,
    invoice_id BIGINT NOT NULL,
    amount_minor BIGINT NOT NULL CHECK (amount_minor > 0),
    payment_method VARCHAR(16) NOT NULL CHECK (payment_method IN ('cash','card','bank_transfer','digital_wallet','other')),
    payment_date DATE NOT NULL,
    reference TEXT NULL,
    notes TEXT NULL,
    is_reversal TINYINT(1) NOT NULL DEFAULT 0,
    reverses_payment_id BIGINT NULL,
    received_by CHAR(36) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
    created_at DATETIME(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6),
    legacy_bill_id BIGINT NULL,
    legacy_source VARCHAR(255) NULL,
    FOREIGN KEY (invoice_id) REFERENCES invoices(id) ON DELETE RESTRICT,
    FOREIGN KEY (reverses_payment_id) REFERENCES invoice_payments(id) ON DELETE RESTRICT,
    INDEX (payment_date, id),
    INDEX (legacy_source, legacy_bill_id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_bin;

CREATE TABLE IF NOT EXISTS membership_fees (
    id BIGINT AUTO_INCREMENT PRIMARY KEY,
    member_id BIGINT NOT NULL,
    billing_month DATE NOT NULL,
    amount_minor BIGINT NOT NULL DEFAULT 0 CHECK (amount_minor >= 0),
    currency_code CHAR(3) NOT NULL DEFAULT 'NPR',
    status VARCHAR(8) NOT NULL DEFAULT 'unpaid' CHECK (status IN ('paid','unpaid','overdue','partial')),
    paid_amount_minor BIGINT NOT NULL DEFAULT 0 CHECK (paid_amount_minor BETWEEN 0 AND amount_minor),
    due_date DATE NOT NULL,
    paid_at DATETIME(6) NULL,
    paid_by CHAR(36) CHARACTER SET ascii COLLATE ascii_bin NULL,
    invoice_id BIGINT NULL,
    notes TEXT NULL,
    created_at DATETIME(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6),
    updated_at DATETIME(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6) ON UPDATE CURRENT_TIMESTAMP(6),
    legacy_officeregister_id BIGINT NULL,
    legacy_source VARCHAR(255) NULL,
    FOREIGN KEY (member_id) REFERENCES members(id) ON DELETE CASCADE,
    FOREIGN KEY (invoice_id) REFERENCES invoices(id) ON DELETE SET NULL,
    UNIQUE (member_id, billing_month),
    INDEX (member_id, status, due_date),
    INDEX (status, due_date),
    INDEX (legacy_source, legacy_officeregister_id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_bin;
