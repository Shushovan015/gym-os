-- Add timestamp columns for activation/deactivation audit
ALTER TABLE public.members
ADD COLUMN IF NOT EXISTS activated_at timestamp with time zone,
ADD COLUMN IF NOT EXISTS deactivated_at timestamp with time zone;

-- Create index for filtering active members
CREATE INDEX IF NOT EXISTS members_is_active_idx ON public.members (is_active) WHERE is_active = true;
CREATE INDEX IF NOT EXISTS members_is_active_all_idx ON public.members (is_active);

-- Create member_status_history table for audit trail
CREATE TABLE IF NOT EXISTS public.member_status_history (
    id bigint NOT NULL GENERATED BY DEFAULT AS IDENTITY,
    member_id bigint NOT NULL REFERENCES public.members(id) ON DELETE CASCADE,
    status text NOT NULL CHECK (status IN ('active', 'inactive')),
    changed_by uuid,
    changed_at timestamp with time zone DEFAULT now() NOT NULL,
    notes text,
    CONSTRAINT member_status_history_pkey PRIMARY KEY (id)
);

ALTER TABLE public.member_status_history OWNER TO postgres;

CREATE INDEX IF NOT EXISTS member_status_history_member_id_idx ON public.member_status_history (member_id);
CREATE INDEX IF NOT EXISTS member_status_history_changed_at_idx ON public.member_status_history (changed_at DESC);

ALTER TABLE public.member_status_history ENABLE ROW LEVEL SECURITY;

CREATE POLICY "member_status_history_select_admin" ON public.member_status_history FOR SELECT TO authenticated USING (public.is_admin());
CREATE POLICY "member_status_history_insert_admin" ON public.member_status_history FOR INSERT TO authenticated WITH CHECK (public.is_admin());

