-- Transformation timeline per member (photo url + milestone).
create table if not exists public.member_transformations (
  id bigint generated by default as identity primary key,
  member_ref bigint not null references public.members(id) on delete cascade,
  captured_at date not null,
  milestone_title text,
  milestone_notes text,
  photo_url text,
  created_at timestamptz not null default now()
