-- Trigger to automatically initialize membership fees for new members
CREATE OR REPLACE FUNCTION public.on_member_created()
RETURNS trigger LANGUAGE plpgsql SECURITY DEFINER SET search_path = public AS $$
BEGIN
    -- Initialize membership fees for the new member
    PERFORM public.initialize_membership_fees(NEW.id);
    RETURN NEW;
END $$;

